import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { rememberBook, segmentVerses, shareText, useIndex } from '../app/js/bible.js';
import { parseUsfm } from '../scripts/lib/usfm.mjs';

const INDEX_PATH = new URL('../app/data/index.json', import.meta.url);
const BSB_DIR = new URL('../app/data/bsb/books/', import.meta.url);
const skip = (!fs.existsSync(INDEX_PATH) && 'app/data/index.json 없음') || (!fs.existsSync(BSB_DIR) && 'BSB 데이터 없음 (npm run bsb)');
const index = skip ? null : useIndex(JSON.parse(fs.readFileSync(INDEX_PATH, 'utf8')));
const bsb = (code) => JSON.parse(fs.readFileSync(new URL(`${code}.json`, BSB_DIR), 'utf8'));

// ── USFM 변환 ─────────────────────────────────────────────

const SAMPLE = String.raw`\id PSA Autogenerated BSB by bsb2usfm
\h Psalm
\toc1 Psalm
\mt1
\c 1
\ms BOOK I
\d Psalms 1–41
\s1 The Two Paths
\r (\ref Matthew 5:3–12|MAT 5:3-12\ref*)
\q1 \v 1 Blessed is the man
\q2 who does not walk in the counsel of the wicked,
\b
\q1 \v 2 But his delight is in the Law of the LORD,\f + \fr 1:2 \ft Or \fqa instruction\ft ; see \ref Joshua 1:8|JOS 1:8\ref*\f*
\q2 and on His law he meditates day and night.
\c 3
\s1 Deliver Me, O LORD!
\d \v 1 A Psalm of David, when he fled from his son Absalom.
\q1 O LORD, how my foes have increased!
\q1 \v 2 Many say of me, “God will not deliver him.” \qs Selah\qs*
\c 119
\qa א
\qa ALEPH
\q1 \v 1 Blessed are those whose way is blameless,
\p \wj \v 2 “Ask,”\wj* He said.\f + \fr 119:2 \ft BYZ and TR include \fqa \fv 3\fv*More words\ft .\f*
`;

test('USFM: 시편 표제·단락 제목·각주를 앱 형식으로', () => {
  const book = parseUsfm(SAMPLE, 'psa');
  assert.equal(book.name, 'Psalm');
  assert.deepEqual(
    book.chapters.map((c) => c.c),
    [1, 3, 119],
  );
  const [c1, c3, c119] = book.chapters;
  // 시 줄은 한 절로 잇고, 관주(\r)는 뺀다
  assert.deepEqual(c1.verses, [
    { v: 1, t: 'Blessed is the man who does not walk in the counsel of the wicked,' },
    { v: 2, t: 'But his delight is in the Law of the LORD, and on His law he meditates day and night.' },
  ]);
  // \ms 다음의 \d는 권 구분이라 단락 제목, 그다음 \s1까지 1절 앞에
  assert.deepEqual(c1.heads, [
    { v: 1, kind: 'section', t: 'BOOK I' },
    { v: 1, kind: 'section', t: 'Psalms 1–41' },
    { v: 1, kind: 'section', t: 'The Two Paths' },
  ]);
  // 각주는 \fr의 절 번호로, \ref는 보이는 글만
  assert.deepEqual(c1.notes, [{ v: 2, n: '1', t: 'Or instruction; see Joshua 1:8' }]);
  // "\d \v 1 표제": 표제는 1절 앞의 제목, 1절 본문은 다음 줄부터
  assert.deepEqual(c3.heads, [
    { v: 1, kind: 'section', t: 'Deliver Me, O LORD!' },
    { v: 1, kind: 'title', t: 'A Psalm of David, when he fled from his son Absalom.' },
  ]);
  assert.equal(c3.verses[0].t, 'O LORD, how my foes have increased!');
  assert.equal(c3.verses[1].t, 'Many say of me, “God will not deliver him.” Selah');
  // 답관체 제목은 하나로, 글자 꾸밈(\wj)은 빼고, 각주의 절 표시(\fv)는 괄호로
  assert.deepEqual(c119.heads, [{ v: 1, kind: 'section', t: 'א ALEPH' }]);
  assert.equal(c119.verses[1].t, '“Ask,” He said.');
  assert.deepEqual(c119.notes, [{ v: 2, n: '1', t: 'BYZ and TR include (3) More words.' }]);
});

// ── BSB 데이터 ────────────────────────────────────────────

test('BSB 66권: 장 수가 새번역과 같고, 모든 절에 본문이 있고, USFM 표지가 남지 않았다', { skip }, () => {
  for (const b of index.books) {
    const data = bsb(b.code);
    assert.equal(data.code, b.code);
    assert.ok(data.name, `${b.code} 영어 이름`);
    assert.equal(data.chapters.length, b.chapters.length, `${b.code} 장 수`);
    data.chapters.forEach((ch, i) => {
      assert.equal(ch.c, i + 1, `${b.code} 장 순서`);
      assert.ok(ch.verses.length, `${b.code} ${ch.c} 절 없음`);
      for (const x of [...ch.verses, ...ch.heads, ...ch.notes]) {
        assert.ok(x.t && !/\\/.test(x.t), `${b.code} ${ch.c}:${x.v} ${JSON.stringify(x.t)}`);
      }
    });
  }
});

test('구간의 절: BSB는 새번역 장의 마지막 절에서 끝나는 구간이면 그 장 끝까지 담는다', { skip }, () => {
  const cor = bsb('2co'); // 고린도후서 13장: 새번역 13절, BSB 14절
  const nums = (list) => list.map((x) => x.v);
  assert.deepEqual(nums(segmentVerses({ b: '2co', c: 13, from: 11, to: 13 }, cor)), [11, 12, 13, 14]);
  assert.deepEqual(nums(segmentVerses({ b: '2co', c: 13, from: 1, to: 3 }, cor)), [1, 2, 3]);
  assert.equal(segmentVerses({ b: '2co', c: 13 }, cor).length, 14);
  // 새번역은 그대로
  const ko = JSON.parse(fs.readFileSync(new URL('../app/data/books/2co.json', import.meta.url), 'utf8'));
  assert.deepEqual(nums(segmentVerses({ b: '2co', c: 13, from: 11, to: 13 }, ko)), [11, 12, 13]);
});

test('BSB 공유: 영어 책 이름과 (BSB)', { skip }, () => {
  rememberBook(bsb('psa'), 'bsb');
  const psa23 = bsb('psa').chapters[22].verses[0];
  assert.equal(
    shareText([{ b: 'psa', c: 23, v: 1, t: psa23.t }], { translation: 'bsb' }),
    'The LORD is my shepherd; I shall not want. - Psalm 23:1 (BSB)',
  );
  // 새번역 공유는 그대로
  assert.equal(shareText([{ b: 'psa', c: 23, v: 1, t: '주님은 나의 목자시니' }]), '주님은 나의 목자시니 - 시편 23:1');
});
