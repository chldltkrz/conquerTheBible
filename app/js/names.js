const pick = (list, random) => list[Math.floor(random() * list.length)];

/** seed가 같으면 늘 같은 차례로 0 이상 1 미만을 내는 random (mulberry32). seed는 0 이상의 정수 */
export function seededRandom(seed) {
  let s = (seed % 2 ** 32 ^ Math.floor(seed / 2 ** 32)) >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 2 ** 32;
  };
}

/**
 * taken에 없는 무작위 이름 "형용사 동물". 거의 다 쓴 경우에는 차례로 찾는다.
 * @param {Iterable<string>} [taken] 이미 쓰는 이름들 (같은 기기의 계정, 같은 방의 멤버)
 * @param {() => number} [random] 0 이상 1 미만 (테스트용)
 */
export function randomName(taken = [], random = Math.random) {
  const used = new Set(taken);
  for (let i = 0; i < 50; i++) {
    const name = `${pick(ADJECTIVES, random)} ${pick(ANIMALS, random)}`;
    if (!used.has(name)) return name;
  }
  for (const a of ADJECTIVES) for (const b of ANIMALS) if (!used.has(`${a} ${b}`)) return `${a} ${b}`;
  return `${pick(ADJECTIVES, random)} ${pick(ANIMALS, random)}`;
}
